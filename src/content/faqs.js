export function faqsForCategory(category) {
  const slug = String(category?.slug || category?.name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-');
  const name = String(category?.name || '').toLowerCase();

  if (CATEGORY_FAQS[slug]) return CATEGORY_FAQS[slug];
  if (name.includes('bell')) return CATEGORY_FAQS['guardian-bells'];
  if (name.includes('boot')) return CATEGORY_FAQS.boots;
  if (name.includes('jacket')) return CATEGORY_FAQS.jackets;
  if (name.includes('glove')) return CATEGORY_FAQS.gloves;
  if (name.includes('hat') || name.includes('cowboy')) return CATEGORY_FAQS.hats;
  if (name.includes('patch')) return CATEGORY_FAQS.patches;
  return CATEGORY_FAQS.default;
}

export function toFaqPageSchema(faqs) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: (faqs || []).map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
}
